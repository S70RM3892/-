# -*- coding: utf-8 -*-
"""自分の得点の「分散」をどちらに動かすべきか。

この研究は一貫して相手側（合格最低点）を分析してきた。しかし p02 で置いた
パラメータを見ると、不確実性の内訳はこうなっている:

    合格最低点の年変動 σ  =  5.7 – 10.6 点
    自分の当日ゆらぎ sp   =  30 – 80 点

**分散でみると自分側が相手側の 10〜200 倍ある。**
つまり合格最低点の分析は、全不確実性の数パーセントを相手にしていたことになる。
前回「戦略分析から新しいものが出てこなかった」のは当然で、
大きい項を一度も見ていなかった。

ここで見るのは、その大きい項の性質である。結論を先に書く:

    合格ラインより下にいる人は、本番の得点の分散を **上げる** べきである。
    上にいる人だけが、分散を下げるべきである。

受験の標準的な助言（ミスをなくせ、確実に取れ、冒険するな）は
**後者にしか当てはまらない。** 分岐点は実力ではなく、ラインとの位置関係で決まる。
"""
from __future__ import annotations

import json
import math
import os

from kyodai import datasets as ds
from kyodai.stats import cdf, header, pdf


def main() -> None:
    params = ds.load_params()
    lad = params["ladder"]
    mu0 = lad["mu_candidate_pt"]["value"]
    sp0 = lad["sigma_performance_pt"]["value"]

    hand = os.path.join(ds.OUTPUTS, "panel_handoff.json")
    if not os.path.exists(hand):
        raise SystemExit("先に p01_panel.py を実行すること")
    noise = json.load(open(hand, encoding="utf-8"))["cutoff_noise_points"]
    sig = noise["情報"]["with_step"]

    print(header("0. 不確実性の内訳"))
    print(f"  合格最低点の年変動 σ          = {noise['情報']['no_step']:.1f}–{sig:.1f} 点")
    print(f"  自分の当日ゆらぎ sp（既定）     = {sp0:.1f} 点")
    print(f"  合成 s = sqrt(sp^2 + σ^2)     = {math.sqrt(sp0**2 + sig**2):.1f} 点")
    lo_share = sig ** 2 / (80 ** 2 + sig ** 2) * 100
    hi_share = sig ** 2 / (30 ** 2 + sig ** 2) * 100
    share = sig ** 2 / (sp0 ** 2 + sig ** 2) * 100
    print(f"  → 全分散に占める『相手側』の割合は {lo_share:.1f}–{hi_share:.1f}%"
          f"（sp=30–80 の範囲、既定 sp={sp0:g} では {share:.1f}%）。")
    print("     残りは全部自分側。8年分のパネルで精密に推定してきたのは、小さい方だった。")

    print(header("1. 分散はどちらに動かすべきか（符号）"))
    print("  合格確率  P = Φ(μ / s)     μ = 自分の実力 − 合格最低点,  s = 合成SD")
    print("  ∂P/∂μ = φ(μ/s)/s          > 0   … 実力を上げるのは常に正しい")
    print("  ∂P/∂s = −φ(μ/s)·μ/s²")
    print()
    print("    μ < 0（ラインより下）→ ∂P/∂s > 0 … 分散を **上げる** と合格確率が上がる")
    print("    μ > 0（ラインより上）→ ∂P/∂s < 0 … 分散を **下げる** べき")
    print("    μ = 0               → 分散は無関係（P=0.5 のまま）")
    print()
    print("  これは『負けている側は賭けに出るべき』という一般則の受験版である。")
    print("  重要なのは、分岐が実力の絶対水準ではなく **ラインとの位置関係** で決まること。")

    print(header("2. 効果の大きさ"))
    print(f"  μ を振り、sp を {30}〜{100} 点で動かしたときの合格確率（σ={sig:.1f}点 固定）")
    sps = [30, 45, 64.5, 80, 100]
    print(f"  {'μ(点)':<8}" + "".join(f"{f'sp={v:g}':>10}" for v in sps) + f"{'最適方向':>12}")
    for mu in (-80, -60, -36.2, -20, 0, 20, 40):
        row = f"  {mu:<8.0f}"
        for sp in sps:
            s = math.sqrt(sp ** 2 + sig ** 2)
            row += f"{cdf(mu / s) * 100:>9.1f}%"
        arrow = "分散を上げる" if mu < 0 else ("どちらでも" if mu == 0 else "分散を下げる")
        row += f"{arrow:>12}"
        print(row)
    print()
    s0 = math.sqrt(sp0 ** 2 + sig ** 2)
    s_low = math.sqrt(45 ** 2 + sig ** 2)
    print(f"  既定の μ={mu0:+.1f} なら、sp を {sp0:g} → 45 に下げると")
    print(f"  合格確率は {cdf(mu0/s0)*100:.1f}% → {cdf(mu0/s_low)*100:.1f}% と "
          f"{(cdf(mu0/s0)-cdf(mu0/s_low))*100:.1f} ポイント **下がる**。")
    print("  『ミスを減らして安定させる』ことが、この位置では逆効果になっている。")

    print(header("3. 交換レート — 期待値をいくら捨てて分散を買えるか"))
    print("  現実の戦略は分散だけを動かせない。難問に時間を賭ければ、")
    print("  確実に取れたはずの点を失う。つまり (dμ<0, ds>0) がセットで来る。")
    print()
    print("  dP > 0 ⟺ dμ > (μ/s)·ds")
    print("  μ<0 のとき右辺は負。したがって期待値の損失をある程度まで許容できる。")
    print()
    print("      許容できる期待値の損失 = |μ/s| × 分散の増加分 = |z| × Δs")
    print()
    print("  |z| は『自分がラインから何σ下にいるか』そのもの。覚えやすい形をしている。")
    print(f"\n  {'μ(点)':<8}{'|z|':>8}{'Δs=+10で許容':>16}{'Δs=+20で許容':>16}{'Δs=+30で許容':>16}")
    for mu in (-80, -60, -36.2, -20, -10):
        s = math.sqrt(sp0 ** 2 + sig ** 2)
        z = abs(mu / s)
        print(f"  {mu:<8.0f}{z:>8.2f}" + "".join(f"{z*d:>15.1f}点" for d in (10, 20, 30)))
    print("\n  読み方: μ=−36点 の人が、本番で得点SDを +20点 増やす戦略を取るなら、")
    print("  期待得点が 11点 下がるところまでは、その戦略の方が合格確率が高い。")

    print(header("4. 『分散を上げる』の具体化"))
    print("  二次試験で分散を上げる方向（= 期待値を少し犠牲にしてよい）:")
    print("    * 数学で部分点狙いをやめ、完答を狙って1問に時間を集中する")
    print("    * 手をつける大問を絞る（6問を薄く回るより3問を深く）")
    print("    * 見慣れない設定の問題を捨てずに取りに行く")
    print("  分散を下げる方向（= μ>0 の人だけが取るべき）:")
    print("    * 検算の徹底、易問の取りこぼし潰し、全問に均等に時間を配る")
    print()
    print("  京大二次の配点構造はこの選択を増幅する。数学は6問200点で1問30–40点、")
    print("  1025点換算で1問 37.5–50.0点。**部分点と完答の差がそのまま大きな分散**になる。")
    print("  共通テストは設問が細かく部分点も無いので、分散を能動的に操作する余地が小さい。")
    print("  つまりこの節の話は、ほぼ二次試験の話である。")

    print(header("5. なぜこれが見落とされていたか"))
    print("  (a) 受験の助言は『合格者の平均像』から作られる。合格者は定義上 μ>0 の人なので、")
    print("      そこから抽出された助言（ミスをなくせ・確実に取れ）は μ>0 用に偏る。")
    print("      生存者バイアスが、助言の向きそのものを歪めている。")
    print("  (b) 分散は事後的に観測できない。1回しか受けないので、")
    print("      『あの戦略は分散が高かった』は本人にも分からない。")
    print(f"  (c) この研究自身も、8年パネルで相手側の分散（全体の {lo_share:.0f}–{hi_share:.0f}%）を"
          "精密に測り、")
    print("      自分側の分散（残り）は出典不明の定数1個で済ませていた。")

    print(header("6. 限界"))
    print(f"  * μ も sp も status=USER。公開情報からは決まらない。")
    print("  * ただし **結論の向きを決めるのは μ の符号だけ** である。")
    print("    符号（ラインの上か下か）は、大きさよりはるかに推定しやすい。")
    print("    この結果は、最も不確かな量に対して頑健であるという点で例外的に使える。")
    print("  * 正規分布を仮定している。実際の得点分布は上に天井があり右に歪まない。")
    print("    天井が近い（μ>0 かつ満点付近）ほど、分散を上げる利得はさらに小さくなる。")
    print("  * (dμ, ds) の実現可能な組合せ（フロンティア）は測っていない。")
    print("    『どの戦略がどれだけ分散を動かすか』は模試の答案を自分で集計するしかない。")
    print("    → 次の作業: 模試の大問別得点を記録し、戦略ごとの (平均, SD) を実測する。")


if __name__ == "__main__":
    main()
